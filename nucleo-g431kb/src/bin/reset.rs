//! What [`Can::reinitialize`] clears, with and without an RCC reset of
//! FDCAN, on the NUCLEO-G431KB with FDCAN1 on PA12 (TX, CN4 pin 5) and PA11
//! (RX, CN4 pin 13), joined by a jumper so that nobody acknowledges:
//!
//! 1. Single-shot frames fail on acknowledgement until the transmit error
//!    counter reaches 128, and one more frame's report is left untaken.
//! 2. `reinitialize` alone drops the untaken report but, as RM0440 says of
//!    `CCCR.INIT`, leaves the error counters.
//! 3. An RCC reset (`FDCANRST`) and `reinitialize` leave them at 0.
//! 4. The controller works after that: in external loopback a frame comes
//!    back and is reported sent, and in normal mode a single-shot frame is
//!    reported failed, the counter at 8.
//!
//! Normal mode drives PA12: only with nothing else on CN4's pins 5 and 13.
//!
//! ```sh
//! cargo run-fdcan-reset
//! ```

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use can_hal::{BusStatus, CanFrame, CanId, ConfirmedTransmit, ErrorCounters, Event, Failure, Frame, Outcome, SamplePoint};
use can_hal_fdcan::{BitTiming, Can, Clock, Config, Mode, Peripheral, State};
use defmt::{Debug2Format, error, info, warn};
use defmt_rtt as _;
use embassy_executor::Spawner;
use embassy_stm32::gpio::{AfType, Flex, OutputType, Pull, Speed};
use embassy_stm32::interrupt::typelevel::{FDCAN1_IT0, Handler, Interrupt};
use embassy_stm32::rcc::{self, Pll, PllMul, PllPreDiv, PllQDiv, PllRDiv, PllSource, Sysclk};
use embassy_time::{Duration, Timer, with_timeout};
use panic_probe as _;

/// FDCAN1's kernel clock: PLL Q, 80 MHz.
const CAN_CLOCK_HZ: u32 = 80_000_000;
const EVENTS: usize = 32;
const BITRATE: u32 = 500_000;
/// How long to wait for a report: a classic frame and its error frame take
/// well under a millisecond at 500 kbit/s.
const REPORT_TIMEOUT: Duration = Duration::from_millis(20);

/// Embassy's time, for the driver's timestamps and timeouts.
struct EmbassyClock;

impl Clock for EmbassyClock {
    type Instant = embassy_time::Instant;

    fn now() -> Self::Instant {
        embassy_time::Instant::now()
    }

    fn deadline(timeout: core::time::Duration) -> Self::Instant {
        let micros = u64::try_from(timeout.as_micros()).unwrap_or(u64::MAX);
        embassy_time::Instant::now().saturating_add(Duration::from_micros(micros))
    }

    fn has_passed(deadline: &Self::Instant) -> bool {
        embassy_time::Instant::now() >= *deadline
    }
}

type Channel = Can<EmbassyClock, EVENTS>;

static STATE: State<EmbassyClock, EVENTS> = State::new();

struct CanInterrupt;

impl Handler<FDCAN1_IT0> for CanInterrupt {
    unsafe fn on_interrupt() {
        STATE.on_interrupt();
    }
}

embassy_stm32::bind_interrupts!(struct Irqs {
    FDCAN1_IT0 => CanInterrupt;
});

/// HSI16 through the PLL: 160 MHz system clock (R), 80 MHz for FDCAN (Q).
fn clocks() -> embassy_stm32::Config {
    let mut config = embassy_stm32::Config::default();
    config.rcc.pll = Some(Pll {
        source: PllSource::HSI,
        prediv: PllPreDiv::DIV4,
        mul: PllMul::MUL80,
        divp: None,
        divq: Some(PllQDiv::DIV4),
        divr: Some(PllRDiv::DIV2),
    });
    config.rcc.sys = Sysclk::PLL1_R;
    config.rcc.boost = true;
    config.rcc.mux.fdcansel = rcc::mux::Fdcansel::PLL1_Q;
    config
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let p = embassy_stm32::init(clocks());

    let mut rx = Flex::new(p.PA11);
    let mut tx = Flex::new(p.PA12);
    if !jumper_joins(&mut rx, &mut tx).await {
        loop {
            Timer::after_secs(1).await;
        }
    }
    rx.set_as_af_unchecked(9, AfType::input(Pull::Up));
    tx.set_as_af_unchecked(9, AfType::output(OutputType::PushPull, Speed::VeryHigh));

    // FDCAN1's bus clock; its kernel clock is PLL Q, by the mux above.
    embassy_stm32::pac::RCC.apb1enr1().modify(|w| w.set_fdcanen(true));
    let _ = embassy_stm32::pac::RCC.apb1enr1().read();

    let nominal = BitTiming::solve_nominal(CAN_CLOCK_HZ, BITRATE, SamplePoint::from_per_mille(875)).unwrap();
    let config = |mode| Config::new(nominal).with_mode(mode).with_retransmit(false);
    // SAFETY: FDCAN1's registers and message RAM on the STM32G4, used by
    // nothing else.
    let peripheral = unsafe { Peripheral::new(0x4000_6400, 0x4000_A400) };
    let mut can = Can::new(peripheral, &STATE, config(Mode::Normal)).unwrap();
    FDCAN1_IT0::unpend();
    // SAFETY: its handler is bound above.
    unsafe { FDCAN1_IT0::enable() };

    let mut failures = 0u32;

    // 1. Error passive by acknowledgement errors, and a report left untaken.
    can.start().unwrap();
    Timer::after_millis(10).await;
    for n in 0..20u8 {
        let _ = send(&mut can, 0x100, n).await;
        if counters(&can).transmit >= 128 {
            break;
        }
    }
    let _ = can.try_transmit(&frame(0x1FF, 0xFF)).unwrap();
    Timer::after_millis(5).await;
    let before = counters(&can);
    info!("1. before: {}, a report untaken", Debug2Format(&before));
    failures += check(before.transmit >= 128, "1. the transmit error counter reached 128");

    // 2. reinitialize alone: the report is gone, the counters are not. The
    // channel counts as error active again, so the counters still at 128
    // bring a fresh BusStateChanged, which is no leftover.
    can.reinitialize(config(Mode::Normal)).unwrap();
    let mut leftovers = 0u32;
    while let Ok(event) = with_timeout(REPORT_TIMEOUT, can.next_event()).await {
        info!("2. after reinitialize: {}", Debug2Format(&event));
        leftovers += u32::from(matches!(event, Event::Transmitted { .. } | Event::Received(_)));
    }
    info!("2. reinitialize alone: {}", Debug2Format(&counters(&can)));
    failures += check(leftovers == 0, "2. no report or frame survives reinitialize");
    failures += check(counters(&can) == before, "2. the counters carry over without a reset (RM0440)");

    // 3. An RCC reset first: the counters go to 0.
    embassy_stm32::pac::RCC.apb1rstr1().modify(|w| w.set_fdcanrst(true));
    embassy_stm32::pac::RCC.apb1rstr1().modify(|w| w.set_fdcanrst(false));
    can.reinitialize(config(Mode::Loopback)).unwrap();
    info!("3. RCC reset and reinitialize: {}", Debug2Format(&counters(&can)));
    failures += check(counters(&can) == ErrorCounters { transmit: 0, receive: 0 }, "3. the counters are 0");

    // 4. It works after: external loopback, then normal mode.
    can.start().unwrap();
    Timer::after_millis(10).await;
    let id = can.try_transmit(&frame(0x123, 0xAA)).unwrap();
    let (mut sent, mut back) = (false, false);
    while let Ok(event) = with_timeout(REPORT_TIMEOUT, can.next_event()).await {
        match event {
            Event::Transmitted { id: done, outcome } if done == id => sent = matches!(outcome, Outcome::Sent(_)),
            Event::Received(received) => back |= matches!(received.frame(), Frame::Can(f) if f.data() == [0xAA]),
            other => info!("4. meanwhile {}", Debug2Format(&other)),
        }
    }
    info!("4. loopback: sent {}, came back {}", sent, back);
    failures += check(sent && back, "4. loopback sends and receives");
    can.reinitialize(config(Mode::Normal)).unwrap();
    can.start().unwrap();
    Timer::after_millis(10).await;
    let outcome = send(&mut can, 0x124, 0xBB).await;
    info!("4. normal, single shot: {}, {}", Debug2Format(&outcome), Debug2Format(&counters(&can)));
    failures += check(outcome == Some(Outcome::Failed(Failure::GaveUp)) && counters(&can).transmit == 8, "4. a single-shot frame fails, the counter at 8");

    if failures == 0 {
        info!("reset: all passed");
    } else {
        error!("reset: {} failures", failures);
    }
    loop {
        Timer::after_secs(1).await;
    }
}

fn frame(id: u16, byte: u8) -> CanFrame {
    CanFrame::new(CanId::new_standard(id).unwrap(), &[byte]).unwrap()
}

fn counters(can: &Channel) -> ErrorCounters {
    can.error_counters().unwrap()
}

/// 1 if `ok` is false, logging `what` either way.
fn check(ok: bool, what: &str) -> u32 {
    if ok {
        info!("ok: {}", what);
        0
    } else {
        error!("FAILED: {}", what);
        1
    }
}

/// Sends a frame and waits for its report.
async fn send(can: &mut Channel, id: u16, byte: u8) -> Option<Outcome<embassy_time::Instant>> {
    let tx = can.try_transmit(&frame(id, byte)).ok()?;
    loop {
        match with_timeout(REPORT_TIMEOUT, can.next_event()).await {
            Ok(Event::Transmitted { id, outcome }) if id == tx => return Some(outcome),
            Ok(_) => {}
            Err(_) => return None,
        }
    }
}

/// Checks the wiring before PA12 is driven, with pulls only: PA12 must read
/// as its pull says (or it's tied to something), and PA11, floating, must
/// follow it (the jumper). True if both hold.
async fn jumper_joins(rx: &mut Flex<'_>, tx: &mut Flex<'_>) -> bool {
    rx.set_as_input(Pull::None);
    for pull in [Pull::Up, Pull::Down, Pull::Up, Pull::Down] {
        tx.set_as_input(pull);
        Timer::after_millis(5).await;
        let high = pull == Pull::Up;
        if tx.is_high() != high {
            warn!("PA12 reads {} on a pull {}: tied to something, not driving it", tx.is_high(), Debug2Format(&pull));
            return false;
        }
        if rx.is_high() != high {
            warn!("PA11 doesn't follow PA12: no jumper from CN4-5 to CN4-13");
            return false;
        }
    }
    info!("jumper: PA11 follows PA12");
    true
}
