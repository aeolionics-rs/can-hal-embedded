//! `can-hal-bxcan` in silent loopback on the 32F072BDISCOVERY, which has no
//! CAN transceiver: silent loopback needs none, the controller feeding its
//! transmitter back to its receiver inside.
//!
//! - Every kind of classic frame (standard and extended IDs, data and
//!   remote, every DLC from 0 to 15) is sent and must come back both as a
//!   received frame and as a transmission reported sent.
//! - Three frames are handed over at once (the three mailboxes), a fourth
//!   must find no room, and the third is aborted: the reports must come in
//!   the order handed over.
//! - Acceptance filters: one standard identifier, a masked range of extended
//!   ones, too many filters refused, cleared, fewer banks from the
//!   configuration, and a bank count out of range refused.
//!
//! On success LD3 (PC6) blinks slowly; on a failure, fast.
//!
//! ```sh
//! cargo run-bxcan-loopback
//! ```

#![no_std]
#![no_main]
// Embassy's main macro passes `_spawner` on to the task it generates, where
// an attribute on `main` doesn't reach.
#![allow(clippy::used_underscore_binding, reason = "in code generated by embassy_executor::main")]

use can_hal::{BusState, BusStatus, CanFrame, CanId, ConfirmedTransmit, Event, Filter, Filterable, Outcome, SamplePoint, Statistics, TransmitId, TryTransmitError};
use can_hal_bxcan::{BitTiming, Can, Clock, Config, Error, FILTER_BANKS, MAX_FILTER_BANKS, Mode, Peripheral, State};
use defmt::{Debug2Format, error, info};
use defmt_rtt as _;
use embassy_executor::Spawner;
use embassy_stm32::gpio::{Level, Output, Speed};
use embassy_stm32::interrupt::typelevel::{CEC_CAN, Handler, Interrupt};
use embassy_stm32::peripherals::CAN;
use embassy_stm32::rcc::{self, Hsi48Config, Sysclk};
use embassy_time::{Duration, Timer, with_timeout};
use panic_probe as _;

/// bxCAN's clock: the APB, from HSI48.
const CAN_CLOCK_HZ: u32 = 48_000_000;
const EVENTS: usize = 32;
const BITRATE: u32 = 500_000;
const TIMEOUT: Duration = Duration::from_millis(100);

/// Embassy's time, for the driver's timestamps and timeouts.
struct EmbassyClock;

impl Clock for EmbassyClock {
    type Instant = embassy_time::Instant;

    fn now() -> Self::Instant {
        embassy_time::Instant::now()
    }

    fn deadline(timeout: core::time::Duration) -> Self::Instant {
        let micros = u64::try_from(timeout.as_micros()).unwrap_or(u64::MAX);
        embassy_time::Instant::now().saturating_add(Duration::from_micros(micros))
    }

    fn has_passed(deadline: &Self::Instant) -> bool {
        embassy_time::Instant::now() >= *deadline
    }
}

type Channel = Can<EmbassyClock, EVENTS>;

static STATE: State<EmbassyClock, EVENTS> = State::new();

struct CanInterrupt;

impl Handler<CEC_CAN> for CanInterrupt {
    unsafe fn on_interrupt() {
        STATE.on_interrupt();
    }
}

embassy_stm32::bind_interrupts!(struct Irqs {
    CEC_CAN => CanInterrupt;
});

#[embassy_executor::main]
async fn main(_spawner: Spawner) {
    let mut config = embassy_stm32::Config::default();
    config.rcc.hsi48 = Some(Hsi48Config::new());
    config.rcc.sys = Sysclk::HSI48;
    let _p = embassy_stm32::init(config);
    let mut led = Output::new(_p.PC6, Level::Low, Speed::Low);
    rcc::enable_and_reset::<CAN>();

    let timing = BitTiming::solve(CAN_CLOCK_HZ, BITRATE, SamplePoint::from_per_mille(875)).unwrap();
    info!("timing {}: {} bit/s", timing, timing.bitrate(CAN_CLOCK_HZ));
    let config = Config::new(timing).with_mode(Mode::SilentLoopback);
    // SAFETY: bxCAN's registers, used by nothing else.
    let peripheral = unsafe { Peripheral::new(embassy_stm32::pac::CAN.as_ptr() as usize) };
    let mut can = Can::new(peripheral, &STATE, config).unwrap();
    CEC_CAN::unpend();
    // SAFETY: its handler is bound above.
    unsafe { CEC_CAN::enable() };
    can.start();

    let mut failures = 0u32;
    failures += every_classic_frame(&mut can).await;
    failures += three_at_once(&mut can).await;
    failures += filters(&mut can, config).await;

    info!("bus state {}, counters {}", Debug2Format(&can.bus_state()), Debug2Format(&can.error_counters()));
    info!("statistics {}", Debug2Format(&can.statistics()));
    if can.bus_state() != Ok(BusState::ErrorActive) {
        error!("not error active");
        failures += 1;
    }
    if failures == 0 {
        info!("loopback: all passed");
    } else {
        error!("loopback: {} failures", failures);
    }
    let period = if failures == 0 { 500 } else { 100 };
    loop {
        led.toggle();
        Timer::after_millis(period).await;
    }
}

fn ids() -> [CanId; 2] {
    [CanId::new_standard(0x123).unwrap(), CanId::new_extended(0x1234_5678).unwrap()]
}

async fn next(can: &mut Channel) -> Option<Event<CanFrame, embassy_time::Instant>> {
    with_timeout(TIMEOUT, can.next_event()).await.ok()
}

/// Sends `frame`: it must be reported sent, and come back received if and
/// only if `passes`.
async fn sent(can: &mut Channel, frame: &CanFrame, passes: bool) -> u32 {
    let tx = match can.try_transmit(frame) {
        Ok(tx) => tx,
        Err(e) => {
            error!("{}: transmit {}", Debug2Format(frame), Debug2Format(&e));
            return 1;
        }
    };
    let (mut received, mut reported) = (false, false);
    while !reported || (passes && !received) {
        match next(can).await {
            Some(Event::Received(r)) if r.frame() == frame && passes => received = true,
            Some(Event::Transmitted { id, outcome: Outcome::Sent(_) }) if id == tx => reported = true,
            other => {
                error!("{} (should pass: {}): sent {}, received {}, then {}", Debug2Format(frame), passes, reported, received, Debug2Format(&other));
                return 1;
            }
        }
    }
    if !passes && let Ok(other) = with_timeout(Duration::from_millis(5), can.next_event()).await {
        error!("{} should be filtered out, then {}", Debug2Format(frame), Debug2Format(&other));
        return 1;
    }
    0
}

async fn every_classic_frame(can: &mut Channel) -> u32 {
    let data = [0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF];
    let (mut frames, mut failures) = (0, 0);
    for id in ids() {
        for dlc in 0..=15 {
            for frame in [CanFrame::new_with_dlc(id, &data[..dlc.min(8)], dlc).unwrap(), CanFrame::new_remote(id, dlc).unwrap()] {
                frames += 1;
                failures += sent(can, &frame, true).await;
            }
        }
    }
    info!("every classic frame: {} frames, {} failures", frames, failures);
    failures
}

/// Three frames handed over at once, a fourth finding no room, and the third
/// aborted: the reports come in the order handed over.
async fn three_at_once(can: &mut Channel) -> u32 {
    let frame = |n: u8| CanFrame::new(CanId::new_standard(0x100 + u16::from(n)).unwrap(), &[n; 8]).unwrap();
    let ids: [TransmitId; 3] = [0, 1, 2].map(|n| can.try_transmit(&frame(n)).unwrap());
    let mut failures = 0;
    if !matches!(can.try_transmit(&frame(3)), Err(TryTransmitError::Full)) {
        error!("a fourth frame found room");
        failures += 1;
    }
    can.abort(ids[2]).unwrap();
    let mut reports = [None; 3];
    let (mut received, mut reported) = (0, 0);
    while reported < 3 {
        match next(can).await {
            Some(Event::Transmitted { id, outcome }) => {
                if id != ids[reported] {
                    error!("report {} for {}, expected {}", reported, Debug2Format(&id), Debug2Format(&ids[reported]));
                    failures += 1;
                }
                reports[reported] = Some(outcome);
                reported += 1;
            }
            Some(Event::Received(_)) => received += 1,
            other => {
                error!("unexpected {}", Debug2Format(&other));
                failures += 1;
                break;
            }
        }
    }
    // The third was aborted in time, or was already on its way and sent.
    let expected = if matches!(reports[2], Some(Outcome::Aborted(_))) { 2 } else { 3 };
    while received < expected {
        if let Some(Event::Received(_)) = next(can).await {
            received += 1;
        } else {
            error!("waiting for frames: {} of {}", received, expected);
            failures += 1;
            break;
        }
    }
    if !reports[..2].iter().all(|o| matches!(o, Some(Outcome::Sent(_)))) {
        error!("the first two weren't both sent");
        failures += 1;
    }
    info!("three at once: reports {}, {} received, {} failures", Debug2Format(&reports), received, failures);
    failures
}

/// Acceptance filters, on the channel `config` sets up.
async fn filters(can: &mut Channel, config: Config) -> u32 {
    let standard = |id: u16| CanFrame::new(CanId::new_standard(id).unwrap(), &[1, 2, 3]).unwrap();
    let extended = |id: u32| CanFrame::new(CanId::new_extended(id).unwrap(), &[4, 5, 6]).unwrap();
    let mut failures = 0;

    // One standard identifier: it passes, its neighbour and extended frames
    // don't.
    let _ = can.set_filters(&[Filter::new(CanId::new_standard(0x123).unwrap(), 0x7FF)]);
    failures += sent(can, &standard(0x123), true).await;
    failures += sent(can, &standard(0x124), false).await;
    failures += sent(can, &extended(0x1234_5678), false).await;

    // A masked range of extended identifiers (the low byte free), and one
    // standard identifier beside it.
    let _ = can.set_filters(&[Filter::new(CanId::new_extended(0x1234_5600).unwrap(), 0x1FFF_FF00), Filter::new(CanId::new_standard(0x700).unwrap(), 0x7FF)]);
    failures += sent(can, &extended(0x1234_5678), true).await;
    failures += sent(can, &extended(0x1234_56FF), true).await;
    failures += sent(can, &extended(0x1234_5778), false).await;
    failures += sent(can, &standard(0x700), true).await;
    failures += sent(can, &standard(0x123), false).await;

    // More filters than banks: refused, and everything accepted.
    let too_many = [const { Filter::new(CanId::Extended(0x100), 0x1FFF_FFFF) }; FILTER_BANKS + 1];
    let refused = can.set_filters(&too_many);
    if refused != Err(Error::TooManyFilters) {
        error!("{} filters: {}", FILTER_BANKS + 1, Debug2Format(&refused));
        failures += 1;
    }
    failures += sent(can, &standard(0x124), true).await;
    failures += sent(can, &extended(0x1234_5778), true).await;

    // Cleared: everything passes.
    let _ = can.set_filters(&[Filter::new(CanId::new_standard(0x123).unwrap(), 0x7FF)]);
    let _ = can.clear_filters();
    failures += sent(can, &standard(0x124), true).await;
    failures += sent(can, &extended(0x0BAD_CAFE), true).await;

    // Two banks from the configuration: two filters fit, three don't.
    if let Err(e) = can.reconfigure(config.with_filter_banks(2)) {
        error!("filters: two banks: {}", Debug2Format(&e));
        return failures + 1;
    }
    can.start();
    let two = [Filter::new(CanId::new_extended(0x1234_5600).unwrap(), 0x1FFF_FF00), Filter::new(CanId::new_standard(0x700).unwrap(), 0x7FF)];
    let _ = can.set_filters(&two);
    failures += sent(can, &extended(0x1234_5678), true).await;
    failures += sent(can, &standard(0x700), true).await;
    failures += sent(can, &extended(0x0BAD_CAFE), false).await;
    let three = [two[0].clone(), two[1].clone(), Filter::new(CanId::Standard(5), 0x7FF)];
    let refused = can.set_filters(&three);
    if refused != Err(Error::TooManyFilters) {
        error!("three filters on two banks: {}", Debug2Format(&refused));
        failures += 1;
    }
    // Out of range: refused, the channel as it was.
    for banks in [0, MAX_FILTER_BANKS + 1] {
        let refused = can.reconfigure(config.with_filter_banks(banks));
        if refused != Err(Error::FilterBanksOutOfRange) {
            error!("{} banks: {}", banks, Debug2Format(&refused));
            failures += 1;
        }
    }
    info!("filters: {} failures", failures);
    failures
}
